"""Turn failed checks into an Ansible playbook. Review before running: it changes system configuration."""
from __future__ import annotations

import yaml

from .checks import FAIL, Result


def _task(r: Result) -> dict | None:
    f = r.fix
    kind = f.get("kind")
    name = f"{r.id}: {r.title}"
    if kind == "sshd":
        return {"name": name, "ansible.builtin.lineinfile": {
            "path": "/etc/ssh/sshd_config", "regexp": f"^\\s*#?\\s*{f['key']}\\b", "line": f"{f['key']} {f['value']}",
            "validate": "sshd -t -f %s"}, "notify": "restart sshd"}
    if kind == "sysctl":
        return {"name": name, "ansible.posix.sysctl": {"name": f["key"], "value": f["value"], "sysctl_file": "/etc/sysctl.d/99-hardening.conf", "reload": True}}
    if kind == "file":
        return {"name": name, "ansible.builtin.file": {"path": f["path"], "mode": f["mode"], "owner": "root"}}
    if kind == "packages_absent" and f.get("names"):
        return {"name": name, "ansible.builtin.apt": {"name": f["names"], "state": "absent", "purge": True}}
    if kind == "packages_present":
        return {"name": name, "ansible.builtin.apt": {"name": f["names"], "state": "present"}}
    return None


def build_playbook(results: list[Result]) -> tuple[str, list[Result]]:
    tasks, manual = [], []
    for r in results:
        if r.status != FAIL:
            continue
        t = _task(r)
        (tasks.append(t) if t else manual.append(r))
    play = [{
        "name": "Apply hardening fixes generated by hardening-audit",
        "hosts": "all",
        "become": True,
        "tasks": tasks,
        "handlers": [{"name": "restart sshd", "ansible.builtin.service": {"name": "ssh", "state": "restarted"}}],
    }]
    header = "# Generated by hardening-audit. REVIEW BEFORE RUNNING. Test with --check --diff first.\n"
    header += "# Requires: ansible.posix collection (ansible-galaxy collection install ansible.posix)\n"
    if manual:
        header += "# Manual follow-up needed:\n" + "".join(f"#   {m.id}: {m.fix.get('note', m.evidence)}\n" for m in manual)
    return header + yaml.safe_dump(play, sort_keys=False, width=120), manual
